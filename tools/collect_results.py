"""Read every study's pins.json and write RESULTS.md: per world / seed /
experiment, the headline table (the numbers the paper reports), n, seeds,
checkpoint sha, run-id, figures."""

from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent


def studies() -> list[str]:
    return sorted(f"{p.parent.parent.name}/{p.parent.name}" for p in (ROOT / "studies").glob("*/*/pins.json"))


def fmt(v) -> str:
    if isinstance(v, float):
        return f"{v:.4g}" if abs(v) < 1e-3 or abs(v) >= 1e4 else f"{v:.3f}"
    return str(v)


def main() -> None:
    out = ["# RESULTS", "", "Generated by `tools/collect_results.py` from each study's `pins.json`.", ""]
    for study in studies():
        pins = json.loads((ROOT / "studies" / study / "pins.json").read_text())
        sj = json.loads((ROOT / "studies" / study / "study.json").read_text())
        ck = (sj.get("checkpoint") or {}).get("sha256", "—")
        out += [f"## {study}", "", f"checkpoint sha256 `{ck}`", ""]
        for exp, run in pins.items():
            d = ROOT / "results" / study / exp / run
            r = json.loads((d / "results.json").read_text())
            m = json.loads((d / "manifest.json").read_text())
            out += [f"### {exp} — `{run}`", "", "| headline | value | n | unit | description |", "|---|---|---|---|---|"]
            for k, h in r["headline"].items():
                out.append(f"| {k} | {fmt(h['value'])} | {h['n']} | {h['unit']} | {h['description']} |")
            figs = ", ".join(f"`{f['path']}`" for f in m.get("figures", []))
            out += ["", f"seeds `{json.dumps(m['seeds'])}` · device {m['device']}", ""]
            if figs:
                out += [f"figures: {figs}", ""]
    (ROOT / "RESULTS.md").write_text("\n".join(out))
    print(f"RESULTS.md: {len(studies())} studies")


if __name__ == "__main__":
    main()
